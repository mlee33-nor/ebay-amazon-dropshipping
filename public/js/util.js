export const $ = (s, el = document) => el.querySelector(s);
export const $$ = (s, el = document) => [...el.querySelectorAll(s)];

export const esc = (s) =>
  String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));

const usd0 = new Intl.NumberFormat('en-US', { style: 'currency', currency: 'USD', maximumFractionDigits: 0 });
const usd2 = new Intl.NumberFormat('en-US', { style: 'currency', currency: 'USD', minimumFractionDigits: 2, maximumFractionDigits: 2 });
const int = new Intl.NumberFormat('en-US');

export const money = (n, dp) => {
  if (n === null || n === undefined || Number.isNaN(n)) return '—';
  const d = dp ?? (Math.abs(n) >= 1000 ? 0 : 2);
  return d === 0 ? usd0.format(n) : usd2.format(n);
};
export const moneyShort = (n) => {
  if (n === null || n === undefined) return '—';
  const a = Math.abs(n);
  const s = n < 0 ? '-' : '';
  if (a >= 1e6) return `${s}$${(a / 1e6).toFixed(2)}M`;
  if (a >= 1e4) return `${s}$${(a / 1e3).toFixed(1)}k`;
  if (a >= 1000) return `${s}$${(a / 1e3).toFixed(2)}k`;
  return `${s}$${a.toFixed(a >= 100 ? 0 : 2)}`;
};
export const pct = (n, dp = 1) => (n === null || n === undefined || !Number.isFinite(n) ? '—' : `${(n * 100).toFixed(dp)}%`);
export const count = (n) => (n === null || n === undefined ? '—' : int.format(Math.round(n)));
export const signed = (n) => (n > 0 ? `+${money(n)}` : money(n));

